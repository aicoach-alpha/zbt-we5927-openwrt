const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const js = fs.readFileSync(path.join(__dirname, '../source/veci-telco-xl-native/files/www/veci/xl-ussd-guide.js'), 'utf8');
const begin = js.indexOf('function transportCode(error)');
const end = js.indexOf('function report(value)', begin);
assert(begin > 0 && end > begin, 'diagnostic classifier found');
const transportCode = vm.runInNewContext(js.slice(begin,end)+'\ntransportCode;', {});
const mk = (msg, n) => ({ message: msg, ubusStatus:n });
assert.equal(transportCode(mk('any',6)), 'ubus_status_6');
assert.equal(transportCode(mk('any',4)), 'ubus_status_4');
assert.equal(transportCode(mk('any',21)), 'transport_unknown');
assert.equal(transportCode(mk('veci.ussd.start timed out')), 'request_timeout');
assert.equal(transportCode(mk('session.access timed out')), 'request_timeout');
assert.equal(transportCode(mk('Not authenticated')), 'session_not_authenticated');
assert.equal(transportCode(mk('HTTP 403')), 'http_4xx');
assert.equal(transportCode(mk('HTTP 502')), 'http_5xx');
assert.equal(transportCode(mk('sensitive-account-or-operator-data')), 'transport_unknown');
assert.equal(transportCode(null), 'transport_unknown');
assert(js.includes("'no_access_field'"));
assert(js.includes("access = transportCode(err)"));
assert(js.includes("call('veci.ussd', 'quotaStatus'"));
assert(js.includes("object: 'veci.ussd', function: 'start'"));
assert(js.includes("report('USSD gagal: ' + text"));
assert(!js.includes("console.log"));
assert.equal((js.match(/window\.confirm\(/g)||[]).length,2);
console.log('VECI_XL_BROWSER_RPC_ERROR_CODES=pass');
console.log('VECI_XL_NO_SENSITIVE_RAW_ERRORS=pass');
